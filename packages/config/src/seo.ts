function withCollection(
  species: SpeciesKeywordConfig,
  collection: SpeciesCollectionSlug
): SpeciesKeywordConfig {
  if (species.collection === collection) {
    return species
  }

  const extraCollections = species.extraCollections ?? []
  if (extraCollections.includes(collection)) {
    return species
  }

  return {
    ...species,
    extraCollections: [...extraCollections, collection],
  }
}

function withoutCollection(
  species: SpeciesKeywordConfig,
  collection: SpeciesCollectionSlug
): SpeciesKeywordConfig {
  const isPrimaryCollection = species.collection === collection
  const nextExtraCollections = (species.extraCollections ?? []).filter(
    (slug) => slug !== collection
  )
  const hasExtraCollectionChanges =
    nextExtraCollections.length !== (species.extraCollections ?? []).length

  if (!isPrimaryCollection && !hasExtraCollectionChanges) {
    return species
  }

  return {
    ...species,
    collection: isPrimaryCollection ? undefined : species.collection,
    extraCollections: nextExtraCollections.length > 0 ? nextExtraCollections : undefined,
  }
}

function inferPrimaryCollection(slug: string): SpeciesCollectionSlug | undefined {
  if (FOOD_COLLECTION_SPECIES_SLUGS.has(slug)) {
    return 'food-and-sweet-treats'
  }
  if (STARTER_BASE_SPECIES_SLUGS.has(slug)) {
    return 'starter-pokemon'
  }

  return undefined
}

function createFallbackSpeciesKeywordConfig(
  entry: (typeof POKEMON_CATALOG)[number]
): SpeciesKeywordConfig {
  const collection = inferPrimaryCollection(entry.slug)

  return {
    slug: entry.slug,
    name: entry.name,
    collection,
    translations: [],
    relatedKeywords: [`${entry.name.toLowerCase()} cards`],
    relatedEntities: [],
    generation: entry.generation,
  }
}

function withAutoCollections(species: SpeciesKeywordConfig): SpeciesKeywordConfig {
  let next = species

  if (!MOST_POPULAR_SPECIES_SLUGS.has(next.slug)) {
    next = withoutCollection(next, 'most-popular')
  }
  if (NON_ANIMAL_SPECIES_SLUGS.has(next.slug)) {
    next = withoutCollection(next, 'all-other-animals')
  }
  if (MOST_POPULAR_SPECIES_SLUGS.has(next.slug)) {
    next = withCollection(next, 'most-popular')
  }
  if (LEGENDARY_SPECIES_SLUGS.has(next.slug)) {
    next = withCollection(next, 'legendary')
  }
  if (MYTHICAL_SPECIES_SLUGS.has(next.slug)) {
    next = withCollection(next, 'mythical')
  }
  if (BABY_SPECIES_SLUGS.has(next.slug)) {
    next = withCollection(next, 'babies')
  }
  if (STARTER_BASE_SPECIES_SLUGS.has(next.slug)) {
    next = withCollection(next, 'starter-pokemon')
  }
  if (FOOD_COLLECTION_SPECIES_SLUGS.has(next.slug)) {
    next = withCollection(next, 'food-and-sweet-treats')
  }

  return next
}

